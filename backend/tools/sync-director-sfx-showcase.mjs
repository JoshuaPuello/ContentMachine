import { promises as fs } from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';
import { config } from 'dotenv';
import { DIRECTOR_SFX_CATALOG } from '../lib/directorSfxCatalog.js';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
config({ path: path.resolve(__dirname, '..', '.env') });

const contentMachineRoot = path.resolve(__dirname, '..', '..');
const sessionId = process.argv[2] || 'director_sfx_showcase';
const outputRoot = path.join(contentMachineRoot, 'output', sessionId);
const storyForgeRoot = path.resolve(
  process.env.STORYFORGE_PATH || path.join(contentMachineRoot, '..', 'storyforge')
);
const publicRoot = path.join(storyForgeRoot, 'public', 'director-sfx', 'showcase');
const canonicalRoot = path.join(publicRoot, 'canonical');
const generatedModule = path.join(
  storyForgeRoot,
  'src',
  'modules',
  'remotion-motion-graphics',
  'director',
  'DirectorSoundDesign.generated.ts'
);

await fs.mkdir(canonicalRoot, { recursive: true });

const soundDesign = {};
const publicManifest = {
  version: 2,
  model: process.env.ELEVENLABS_SFX_MODEL || 'eleven_text_to_sound_v2',
  purpose: 'Canonical, narration-safe sound design for every existing Director Lab item',
  presets: [],
};
const missing = [];

for (const item of DIRECTOR_SFX_CATALOG) {
  const syncedCues = [];
  for (const cue of item.cues) {
    const cueRoot = path.join(outputRoot, 'sfx', cue.id);
    const manifestPath = path.join(cueRoot, 'manifest.json');
    let manifest;
    try {
      manifest = JSON.parse(await fs.readFile(manifestPath, 'utf8'));
    } catch {
      missing.push(`${cue.id}: generation manifest missing`);
      continue;
    }
    const selected = (manifest.options || []).find(
      (option) => option.id === manifest.selectedOptionId
    ) || manifest.options?.[0];
    if (!selected?.url) {
      missing.push(`${cue.id}: no accepted option`);
      continue;
    }
    const sourceName = selected.url.split('/').filter(Boolean).at(-1);
    const sourcePath = path.join(cueRoot, sourceName);
    const targetName = `${cue.id}.mp3`;
    const targetPath = path.join(canonicalRoot, targetName);
    try {
      await fs.copyFile(sourcePath, targetPath);
    } catch {
      missing.push(`${cue.id}: selected audio file missing`);
      continue;
    }

    const generatedCue = {
      file: `director-sfx/showcase/canonical/${targetName}`,
      anchor: Number(selected.anchor_seconds) || 0,
      frames: cue.frames,
      volume: Number((10 ** (cue.gain_db / 20)).toFixed(6)),
    };
    syncedCues.push(generatedCue);
    publicManifest.presets.push({
      preset_id: item.presetId,
      cue_id: cue.id,
      role: cue.role,
      frames: cue.frames,
      file: `canonical/${targetName}`,
      provider: selected.provider,
      gain_db: cue.gain_db,
      duration_seconds: selected.duration_seconds,
      anchor_seconds: selected.anchor_seconds,
      analysis: selected.analysis,
    });
  }
  if (syncedCues.length) soundDesign[item.presetId] = syncedCues;
}

if (missing.length) {
  throw new Error(`Cannot sync incomplete Director sound catalog:\n${missing.join('\n')}`);
}

const generatedSource = `/**
 * AUTO-GENERATED by ContentMachine/backend/tools/sync-director-sfx-showcase.mjs.
 * Edit directorSfxCatalog.js and regenerate instead of editing this file.
 */
export type DirectorSoundCue = {
  file: string;
  anchor: number;
  frames: number[];
  volume: number;
};

export const DIRECTOR_SOUND_DESIGN: Record<string, DirectorSoundCue[]> = ${JSON.stringify(soundDesign, null, 2)};
`;

await fs.writeFile(generatedModule, generatedSource);
await fs.writeFile(
  path.join(publicRoot, 'manifest.json'),
  `${JSON.stringify(publicManifest, null, 2)}\n`
);

process.stdout.write(
  `Synced ${publicManifest.presets.length} analyzed cues across ${Object.keys(soundDesign).length} Director items.\n`
);
